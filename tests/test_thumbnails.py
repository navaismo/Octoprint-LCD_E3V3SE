"""Embedded preview regression tests: python -m unittest discover -s tests."""
import base64
import importlib.util
import io
from pathlib import Path
import textwrap
import unittest
from unittest.mock import patch

from PIL import Image


SPEC = importlib.util.spec_from_file_location(
    "lcd_thumbnails_test", Path(__file__).resolve().parents[1]
    / "octoprint_LCD_E3V3SE" / "thumbnails.py")
thumbnails = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(thumbnails)


def image_data(size=(96, 96), image_format="PNG"):
    stream = io.BytesIO()
    Image.new("RGB", size, (220, 30, 50)).save(stream, format=image_format)
    return base64.b64encode(stream.getvalue()).decode("ascii")


def comments(payload):
    return "\n".join("; " + line for line in textwrap.wrap(payload, 78))


def block(payload, size="96x96", kind="thumbnail"):
    return "; {} begin {} {}\n{}\n; {} end\n".format(
        kind, size, len(payload), comments(payload), kind)


class ThumbnailTests(unittest.TestCase):
    def extract(self, content, fallback=False):
        return thumbnails.extract_thumbnail(io.StringIO(content), allow_fallback=fallback)

    def test_png_and_jpeg_markers_need_no_slicer_identification(self):
        for image_format, kind in (("PNG", "thumbnail"), ("PNG", "thumbnail_PNG"),
                                   ("JPEG", "thumbnail_JPG"), ("JPEG", "thumbnail_JPEG")):
            with self.subTest(kind=kind):
                payload = image_data(image_format=image_format)
                self.assertEqual(self.extract(block(payload, kind=kind)), payload)

    def test_orca_recovery_selects_largest_source_instead_of_96_jpeg(self):
        small = image_data((16, 16))
        jpeg = image_data(image_format="JPEG")
        large = image_data((300, 400))
        content = "; generated by OrcaSlicer 2.3.0\n" + "".join(
            "; THUMBNAIL_BLOCK_START\n;\n" + value + "; THUMBNAIL_BLOCK_END\n"
            for value in (block(small, "16x16"), block(jpeg, kind="thumbnail_JPG"),
                          block(large, "300x400")))
        self.assertEqual(self.extract(content), jpeg)
        self.assertEqual(self.extract(content, True), large)

    def test_bare_base64_requires_fallback_and_works_at_eof(self):
        for image_format in ("PNG", "JPEG"):
            with self.subTest(image_format=image_format):
                payload = image_data(image_format=image_format)
                content = "G28\n; Preview data\n" + comments(payload)
                self.assertIsNone(self.extract(content))
                self.assertEqual(self.extract(content, True), payload)

    def test_other_dimensions_require_fallback_and_largest_wins(self):
        small = image_data((16, 16))
        large = image_data((300, 400))
        content = block(small, "16x16") + block(large, "300x400")
        self.assertIsNone(self.extract(content))
        self.assertEqual(self.extract(content, True), large)

    def test_missing_or_mismatched_end_requires_fallback(self):
        payload = image_data()
        content = block(payload).replace("; thumbnail end", "; thumbnail_PNG end")
        self.assertIsNone(self.extract(content))
        self.assertEqual(self.extract(content, True), payload)

    def test_invalid_candidate_does_not_hide_a_valid_preview(self):
        valid = image_data()
        invalid = base64.b64encode(b"not an image").decode("ascii")
        truncated = image_data(image_format="JPEG")[:80]
        content = block(invalid) + block(truncated, kind="thumbnail_JPG") + block(valid)
        self.assertEqual(self.extract(content), valid)
        self.assertEqual(self.extract(content, True), valid)

    def test_hash_and_uncommented_data_are_not_images(self):
        for content in ("; thumbnail hash: d41d8cd98f00b204e9800998ecf8427e\nG28\n",
                        image_data(), "; /9j/notanimage==\nG28\n"):
            self.assertIsNone(self.extract(content, True))

    def test_crlf_indentation_and_uppercase_markers(self):
        payload = image_data()
        content = block(payload, kind="THUMBNAIL_PNG").replace("\n", "\r\n")
        content = "\r\n".join(" \t" + line for line in content.splitlines())
        self.assertEqual(self.extract(content), payload)

    def test_declared_dimensions_do_not_override_actual_dimensions(self):
        payload = image_data((16, 16))
        self.assertIsNone(self.extract(block(payload)))
        self.assertEqual(self.extract(block(payload), True), payload)

    def test_oversized_candidate_is_skipped(self):
        payload = image_data()
        with patch.object(thumbnails, "_MAX_ENCODED_SIZE", len(payload)):
            content = block("iVBORw0KGgo" + "A" * (len(payload) * 2)) + block(payload)
            self.assertEqual(self.extract(content, True), payload)


if __name__ == "__main__":
    unittest.main()
